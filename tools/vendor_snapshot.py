"""Create the vendored OpenCRG snapshot under ``src/pycrg/vendor/opencrg``.

The snapshot consists of the OpenCRG C base library (headers and sources) plus
the upstream ``LICENSE`` and ``NOTICE`` files. After copying, the patches in
``tools/vendor_patches`` are applied in file-name order with ``git apply`` and a
``VENDOR.md`` file records where the snapshot came from.

Usage::

    python tools/vendor_snapshot.py --source ../OpenCRG          # refresh
    python tools/vendor_snapshot.py --source ../OpenCRG --check  # verify only

``--check`` rebuilds the snapshot in a temporary directory and fails if it
differs from the committed one, which makes the vendored code reproducible from
an upstream checkout.
"""

from __future__ import annotations

import argparse
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEST_REL = Path("src") / "pycrg" / "vendor" / "opencrg"
PATCH_DIR = PROJECT_ROOT / "tools" / "vendor_patches"
UPSTREAM_URL = "https://github.com/asam-ev/OpenCRG"


def _git(source: Path, *args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", "-C", str(source), *args],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip()


def _copy_text(source: Path, target: Path) -> None:
    """Copy a text file, normalising line endings to LF so patches apply."""
    target.parent.mkdir(parents=True, exist_ok=True)
    data = source.read_bytes().replace(b"\r\n", b"\n")
    target.write_bytes(data)


def _collect_sources(source_root: Path) -> list[tuple[Path, Path]]:
    required = [
        Path("LICENSE"),
        Path("NOTICE"),
        Path("c-api/baselib/inc/crgBaseLib.h"),
        Path("c-api/baselib/inc/crgBaseLibPrivate.h"),
    ]
    missing = [str(source_root / rel) for rel in required if not (source_root / rel).exists()]
    if missing:
        raise FileNotFoundError("Required OpenCRG files missing:\n" + "\n".join(missing))

    inc_dir = source_root / "c-api" / "baselib" / "inc"
    src_dir = source_root / "c-api" / "baselib" / "src"
    c_files = sorted(src_dir.glob("*.c"))
    if not c_files:
        raise FileNotFoundError(f"No C sources found under {src_dir}")

    files = [Path("LICENSE"), Path("NOTICE")]
    files += [path.relative_to(source_root) for path in sorted(inc_dir.glob("*.h"))]
    files += [path.relative_to(source_root) for path in c_files]
    return [(source_root / rel, rel) for rel in files]


def _apply_patches(dest_root: Path) -> list[str]:
    patches = sorted(PATCH_DIR.glob("*.patch"))
    # Inside a repository (such as this one), "git apply" resolves paths against
    # the repository root and silently skips the patch; stop the repository
    # search at the snapshot directory so the paths are relative to it.
    env = dict(os.environ, GIT_CEILING_DIRECTORIES=str(dest_root.parent))
    for patch in patches:
        result = subprocess.run(
            ["git", "apply", "--verbose", "--whitespace=nowarn", "-p1", str(patch)],
            cwd=dest_root,
            env=env,
            capture_output=True,
            text=True,
        )
        output = result.stdout + result.stderr
        if result.returncode != 0 or "Skipped patch" in output:
            raise RuntimeError(f"Patch {patch.name} does not apply to this OpenCRG version:\n{output}")
    return [patch.name for patch in patches]


def _write_vendor_info(dest_root: Path, source_root: Path, patch_names: list[str]) -> None:
    commit = _git(source_root, "rev-parse", "HEAD") or "unknown"
    lines = [
        "# Vendored OpenCRG C API",
        "",
        "This directory is generated by `tools/vendor_snapshot.py`; do not edit it by hand.",
        "",
        f"- Upstream: {UPSTREAM_URL}",
        f"- Commit: `{commit}`",
        "- Contents: `c-api/baselib/inc`, `c-api/baselib/src`, `LICENSE`, `NOTICE`",
        "",
        "The files are distributed under the Apache License 2.0 (see `LICENSE` and `NOTICE`).",
        "Files changed by pycrg carry a notice saying so at the top. The changes are kept as",
        "patches in `tools/vendor_patches`:",
        "",
    ]
    lines += [f"- `{name}`" for name in patch_names] or ["- (none)"]
    (dest_root / "VENDOR.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_snapshot(source_root: Path, dest_root: Path, apply_patches: bool = True) -> None:
    sources = _collect_sources(source_root)
    if dest_root.exists():
        shutil.rmtree(dest_root)
    for src, rel in sources:
        _copy_text(src, dest_root / rel)
    patch_names = _apply_patches(dest_root) if apply_patches else []
    _write_vendor_info(dest_root, source_root, patch_names)


def _diff_trees(expected: Path, actual: Path) -> list[str]:
    problems: list[str] = []

    def walk(cmp: filecmp.dircmp, prefix: Path) -> None:
        problems.extend(f"only in rebuilt snapshot: {prefix / name}" for name in cmp.left_only)
        problems.extend(f"only in committed snapshot: {prefix / name}" for name in cmp.right_only)
        _, mismatch, errors = filecmp.cmpfiles(cmp.left, cmp.right, cmp.common_files, shallow=False)
        problems.extend(f"differs: {prefix / name}" for name in mismatch + errors)
        for name, sub in cmp.subdirs.items():
            walk(sub, prefix / name)

    walk(filecmp.dircmp(expected, actual), Path())
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Create the vendored OpenCRG snapshot from an OpenCRG clone.")
    parser.add_argument("--source", required=True, help="path to a local clone of the OpenCRG repository")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write anything; fail if the committed snapshot differs from a fresh one",
    )
    parser.add_argument(
        "--no-patches",
        action="store_true",
        help="copy the upstream files without applying tools/vendor_patches (for writing new patches)",
    )
    args = parser.parse_args()

    source_root = Path(args.source).resolve()
    dest_root = PROJECT_ROOT / DEST_REL

    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            rebuilt = Path(tmp) / "opencrg"
            build_snapshot(source_root, rebuilt, apply_patches=not args.no_patches)
            problems = _diff_trees(rebuilt, dest_root)
        if problems:
            print("Vendored snapshot is out of date:", *problems, sep="\n  ", file=sys.stderr)
            return 1
        print(f"Vendored snapshot matches {source_root}")
        return 0

    build_snapshot(source_root, dest_root, apply_patches=not args.no_patches)
    print(f"Vendor snapshot updated from: {source_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
